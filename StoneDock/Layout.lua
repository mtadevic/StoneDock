local _, SD = ...

local function available()
    return C_EditMode and C_EditMode.GetLayouts and C_EditMode.SaveLayouts
        and C_EditMode.OnLayoutAdded and C_EditMode.SetActiveLayout
        and EditModePresetLayoutManager
        and EditModePresetLayoutManager.GetCopyOfPresetLayouts
        and Enum and Enum.EditModeSystem
end

function SD:GetFullLayouts()
    if not available() then return nil, "Blizzard Edit Mode is not available yet. Try again after entering the world." end
    -- GetLayouts returns CUSTOM layouts, but activeLayout uses the complete
    -- preset + account + character index space, as Blizzard's manager does.
    local saved = C_EditMode.GetLayouts()
    if not saved or not saved.layouts then return nil, "The client has not supplied layout data yet." end
    local result = {}
    for key,value in pairs(saved)do if key~="layouts" then result[key]=SD.Copy(value)end end
    result.layouts = EditModePresetLayoutManager:GetCopyOfPresetLayouts()
    local presetCount = #result.layouts
    for _, layout in ipairs(saved.layouts) do
        if layout.layoutType ~= Enum.EditModeLayoutType.Preset then
            table.insert(result.layouts, SD.Copy(layout))
        end
    end
    return result, nil, presetCount
end

function SD:GetActiveLayout()
    if not available() then return nil end
    local saved=C_EditMode.GetLayouts()
    if not saved or not saved.layouts then return nil end
    local count=self.presetLayoutCount
    if not count or saved.activeLayout<=count then
        local presets=EditModePresetLayoutManager:GetCopyOfPresetLayouts()
        count=#presets self.presetLayoutCount=count
        if saved.activeLayout<=count then return presets[saved.activeLayout] end
    end
    local index=count
    for _,layout in ipairs(saved.layouts)do
        if layout.layoutType~=Enum.EditModeLayoutType.Preset then
            index=index+1
            if index==saved.activeLayout then return SD.Copy(layout) end
        end
    end
end

function SD:IsOurLayoutActive()
    if not available() then return false end
    -- A visibility check must not clone every system in every saved layout.
    local saved=C_EditMode.GetLayouts()
    if not saved or not saved.layouts then return false end
    if not self.presetLayoutCount then
        self.presetLayoutCount=#EditModePresetLayoutManager:GetCopyOfPresetLayouts()
    end
    local index=self.presetLayoutCount
    for _,layout in ipairs(saved.layouts) do
        if layout.layoutType~=Enum.EditModeLayoutType.Preset then
            index=index+1
            if index==saved.activeLayout then return layout.layoutName==self.layoutName end
        end
    end
    return false
end

local function findSystem(layout, system, index)
    for _, info in ipairs(layout.systems or {}) do
        if info.system == system and (index == nil or info.systemIndex == index) then return info end
    end
end

local function anchor(info, point, relativePoint, x, y)
    if not info then return end
    info.anchorInfo = {
        point = point, relativeTo = "UIParent", relativePoint = relativePoint,
        offsetX = x, offsetY = y,
    }
    -- A preset's second anchor can otherwise stretch the custom-position frame.
    info.anchorInfo2 = nil
    info.isInDefaultPosition = false
end

local function rawSetting(info, setting, value)
    if not info or setting == nil then return false end
    for _, current in ipairs(info.settings or {}) do
        if current.setting == setting then
            current.value = value
            return true
        end
    end
    -- Do not add unsupported settings to this client's systems.
    return false
end

local function displaySetting(info, setting, value)
    if not info or setting == nil then return end
    local manager = EditModeSettingDisplayInfoManager
    local map = manager and manager:GetSystemSettingDisplayInfoMap(info.system)
    local definition = map and map[setting]
    if definition then
        if definition.ClampValue then value = definition:ClampValue(value) end
        if definition.stepSize and definition.stepSize > 0 then
            value = definition.minValue + math.floor((value - definition.minValue) / definition.stepSize + 0.5) * definition.stepSize
        end
        if definition.ConvertValue then value = definition:ConvertValue(value, false) end
        rawSetting(info, setting, value)
    end
end

SD.UnitLayoutHelpers = {find=findSystem, anchor=anchor, setting=displaySetting}

-- Upgrade only the exact far-edge anchors generated by early builds. A user's
-- Edit Mode changes (including size/settings) must survive client upgrades.
function SD:UpgradeDefaultUnitAnchors(systems, g)
    if not self.db.arrangeUnits then return false end
    g = g or self:GetGeometry()
    local U = Enum.EditModeUnitFrameSystemIndices
    local changed = false
    for _, info in ipairs(systems or {}) do
        if info.system == Enum.EditModeSystem.UnitFrame then
            local a = info.anchorInfo
            local oldX, point, x, y
            if info.systemIndex == U.Player then
                oldX, point, x, y = 24, "BOTTOMLEFT", g.player.x, g.player.y
            elseif info.systemIndex == U.Target then
                oldX, point, x, y = 1896, "BOTTOMRIGHT", g.target.x, g.target.y
            elseif info.systemIndex == U.Focus then
                oldX, point, x, y = 1621, "BOTTOMRIGHT", g.target.x + 200, g.target.y + 72*g.density
            end
            if g.variant=="gulveig" and a and a.relativeTo=="UIParent" and a.relativePoint=="BOTTOMLEFT" then
                local legacy=info.systemIndex==U.Player and 210 or (info.systemIndex==U.Target and 1710)
                local frame=info.systemIndex==U.Player and PlayerFrame or TargetFrame
                local frameScale=frame and frame:GetScale() or 1
                if legacy and (math.abs(a.offsetX-legacy*g.scale)<1
                    or math.abs(a.offsetX-legacy*g.scale/math.max(frameScale,.01))<1) then
                    anchor(info,point,"BOTTOMLEFT",x*g.scale,y*g.scale)
                    changed=true
                end
            end
            if oldX and a and a.point == point and a.relativePoint == "BOTTOMLEFT"
                and a.relativeTo == "UIParent" and math.abs(a.offsetX-oldX*g.scale)<0.25
                and math.abs(a.offsetY-254*g.density*g.scale)<0.25 then
                anchor(info, point, "BOTTOMLEFT", x*g.scale, y*g.scale)
                changed = true
            end
        end
    end
    return changed
end

local function geometryStamp(g)
    return {width=g.width, height=g.height, scale=g.scale, density=g.density, revision=g.revision, trackingAtWells=true}
end

local function sameGeometry(a, b)
    return a and a.width == b.width and a.height == b.height and a.density == b.density and (a.revision or 0)==(b.revision or 0)
end

function SD:NeedsGeometryAlignment()
    local saved = self.db.nativeGeometry
    return not sameGeometry(saved, self:GetGeometry())
        or (self.db.arrangeUtility and saved and not saved.trackingAtWells)
end

local function rebaseAnchor(a, old, new)
    if not a or a.relativeTo ~= "UIParent" or not a.relativePoint then return end
    local vertical = a.relativePoint:find("TOP") and 1
        or (a.relativePoint:find("BOTTOM") and 0 or 0.5)
    if type(a.offsetX) == "number" then a.offsetX = a.offsetX * new.width / old.width end
    if type(a.offsetY) == "number" then
        local heightFromBottom = a.offsetY + old.height * vertical
        a.offsetY = heightFromBottom * (new.scale * new.density) / (old.scale * old.density)
            - new.height * vertical
    end
end

function SD:BuildLayout(base, geometry, dashboardOnly, previousGeometry)
    local layout = SD.Copy(base)
    layout.layoutName = self.layoutName
    layout.layoutType = Enum.EditModeLayoutType.Account
    layout.layoutIndex = nil
    if Enum.InputDeviceInterfaceType then layout.interfaceStyle = Enum.InputDeviceInterfaceType.Mkb end
    local g, E = geometry or self:GetGeometry(), Enum.EditModeSystem
    local s = g.scale
    local A = Enum.EditModeActionBarSetting
    local nativeButtonSize = (ActionButton1 and ActionButton1:GetWidth()) or 45
    -- Size every native row to its well. Minimum/step limits are owned by Blizzard.
    local targetWidth = g.leftWell.w * s - 22 * s
    local iconPercent = ((targetWidth - 11 * 2) / 12) / nativeButtonSize * 100
    iconPercent = math.floor(iconPercent / 10) * 10
    for _, bar in ipairs(g.bars) do
        local info = findSystem(layout, E.ActionBar, bar.index)
        anchor(info, "CENTER", "BOTTOMLEFT", bar.x * s, bar.y * s)
        displaySetting(info, A.Orientation, Enum.ActionBarOrientation.Horizontal)
        displaySetting(info, A.NumRows, bar.rows or 1)
        -- NumIcons is consumed as a raw integer by UpdateSystemSettingNumIcons.
        -- Do not quantize it through a client-specific display slider step.
        rawSetting(info, A.NumIcons, bar.icons or 12)
        displaySetting(info, A.IconSize, bar.iconSize and bar.iconSize*s/nativeButtonSize*100 or iconPercent)
        displaySetting(info, A.IconPadding, bar.iconPadding or 2)
        displaySetting(info, A.AlwaysShowButtons, 1)
        displaySetting(info, A.HideBarArt, 1)
        displaySetting(info, A.HideBarScrolling, 1)
        if self.db.useExtraBars then
            displaySetting(info, A.VisibleSetting, Enum.ActionBarVisibleSetting.Always)
        end
    end
    -- Hide inherited extra rows in this layout only, so a prior multi-column
    -- layout cannot leave bars over the chat well. Their action slots stay intact.
    if self.db.useExtraBars then
        for index = #g.bars+1, 8 do
            displaySetting(findSystem(layout, E.ActionBar, index), A.VisibleSetting, Enum.ActionBarVisibleSetting.Hidden)
        end
    end
    -- Never delete actions, change action pages, or bind keys.
    local leftCenter = g.leftWell.x + g.leftWell.w / 2 - 960
    local rightCenter = g.rightWell.x + g.rightWell.w / 2 - 960
    -- Edge anchors keep short stance rows and full pet rows aligned as their
    -- button count changes. Follow the action wells' width and offset controls.
    for _, entry in ipairs({
        {11,"BOTTOMRIGHT",g.leftWell.x+g.leftWell.w-12,g.leftWell.y+g.leftWell.h-18*g.density},
        {12,"BOTTOMLEFT",g.rightWell.x+12,g.rightWell.y+g.rightWell.h-18*g.density},
        {13,"BOTTOMLEFT",g.rightWell.x+12,g.rightWell.y+g.rightWell.h-18*g.density},
    }) do
        local info=findSystem(layout,E.ActionBar,entry[1])
        anchor(info,entry[2],"BOTTOMLEFT",entry[3]*s,entry[4]*s)
        displaySetting(info,A.Orientation,Enum.ActionBarOrientation.Horizontal)
        displaySetting(info,A.NumRows,1)
        displaySetting(info,A.IconSize,60)
        displaySetting(info,A.IconPadding,0)
    end

    local minimap = findSystem(layout, E.Minimap)
    local mapContainer = MinimapCluster and MinimapCluster.MinimapContainer
    -- The cluster is a ResizeLayoutFrame: its width already reflects the current
    -- child scale. Measure the unscaled container so rebuilding is idempotent.
    local mapWidth = (mapContainer and mapContainer:GetWidth()) or 215
    local mapPercent = (g.map.w - 10) * s / mapWidth * 100
    displaySetting(minimap, Enum.EditModeMinimapSetting.Size, mapPercent)
    displaySetting(minimap, Enum.EditModeMinimapSetting.HeaderUnderneath, 1)
    anchor(minimap, "CENTER", "BOTTOM", (g.map.x+g.map.w/2-960)*s-10, (g.map.y + g.map.h / 2 + 24*g.density) * s + 15)

    if self.db.arrangeChat and not dashboardOnly then
        local chat = findSystem(layout, E.ChatFrame)
        local c = Enum.EditModeChatFrameSetting
        local w, h = math.floor(g.chat.w * s), math.floor(g.chat.h * s)
        anchor(chat, "BOTTOMLEFT", "BOTTOMLEFT", g.chat.x * s, g.chat.y * s)
        rawSetting(chat, c.WidthHundreds, math.floor(w / 100))
        rawSetting(chat, c.WidthTensAndOnes, w % 100)
        rawSetting(chat, c.HeightHundreds, math.floor(h / 100))
        rawSetting(chat, c.HeightTensAndOnes, h % 100)
    end

    local U = Enum.EditModeUnitFrameSystemIndices
    local US = Enum.EditModeUnitFrameSetting
    if self.db.arrangeUnits and not dashboardOnly then
        local player = findSystem(layout, E.UnitFrame, U.Player)
        local target = findSystem(layout, E.UnitFrame, U.Target)
        local focus = findSystem(layout, E.UnitFrame, U.Focus)
        anchor(player, "BOTTOMLEFT", "BOTTOMLEFT", g.player.x * s, g.player.y * s)
        anchor(target, "BOTTOMRIGHT", "BOTTOMLEFT", g.target.x * s, g.target.y * s)
        anchor(focus, "BOTTOMRIGHT", "BOTTOMLEFT", (g.target.x + 200) * s, (g.target.y + 72*g.density) * s)
        displaySetting(player, US.FrameSize, 100 * s)
        displaySetting(target, US.FrameSize, 100 * s)
        displaySetting(focus, US.FrameSize, 100 * s)
        displaySetting(player, US.CastBarUnderneath, 0)
        displaySetting(target, US.BuffsOnTop, 1)
        local pet = findSystem(layout, E.UnitFrame, U.Pet)
        anchor(pet, "BOTTOMLEFT", "BOTTOMLEFT", 255 * s, 251 * g.density * s)
    end
    if self.db.arrangeGroups and not dashboardOnly then
        local party = findSystem(layout, E.UnitFrame, U.Party)
        local raid = findSystem(layout, E.UnitFrame, U.Raid)
        anchor(party, "BOTTOMLEFT", "BOTTOMLEFT", g.party.x * s, g.party.y * s)
        displaySetting(party, US.UseRaidStylePartyFrames, 1)
        displaySetting(party, US.UseHorizontalGroups, 1)
        displaySetting(party, US.ShowPartyFrameBackground, 0)
        displaySetting(party, US.FrameWidth, 108)
        displaySetting(party, US.FrameHeight, 36)
        displaySetting(party, US.FrameSize, 100 * s)
        anchor(raid, "TOPLEFT", "BOTTOMLEFT", g.raid.x * s, g.raid.y * s)
        local groupType = Enum.RaidGroupDisplayType
        if groupType then displaySetting(raid, US.RaidGroupDisplayType, groupType.SeparateGroupsVertical) end
        displaySetting(raid, US.RowSize, 5)
        displaySetting(raid, US.FrameWidth, 108)
        displaySetting(raid, US.FrameHeight, 36)
        displaySetting(raid, US.FrameSize, 100 * s)
    end

    if not dashboardOnly then
        local cast = findSystem(layout, E.CastBar)
        anchor(cast, "BOTTOM", "BOTTOM", 0, g.cast.y * s)
        displaySetting(cast, Enum.EditModeCastBarSetting.LockToPlayerFrame, 0)
        displaySetting(cast, Enum.EditModeCastBarSetting.BarSize, 100 * s)
    end

    if self.db.arrangeUtility then
        local micro = findSystem(layout, E.MicroMenu)
        anchor(micro, "CENTER", "BOTTOMLEFT", (g.menuDrawer.x + g.menuDrawer.w / 2) * s, (g.menuDrawer.y + g.menuDrawer.h / 2) * s)
        displaySetting(micro, Enum.EditModeMicroMenuSetting.Orientation, Enum.MicroMenuOrientation.Horizontal)
        local menuWidth = MicroMenu and MicroMenu:GetWidth() or 329
        local menuHeight = MicroMenu and MicroMenu:GetHeight() or 40
        displaySetting(micro, Enum.EditModeMicroMenuSetting.Size,
            math.min((g.menuDrawer.w-30)*s/math.max(menuWidth,1), (g.menuDrawer.h-10)*s/math.max(menuHeight,1))*100)
        local bags = findSystem(layout, E.Bags)
        anchor(bags, "CENTER", "BOTTOMLEFT", (g.bagDrawer.x + g.bagDrawer.w / 2) * s, (g.bagDrawer.y + g.bagDrawer.h / 2) * s)
        displaySetting(bags, Enum.EditModeBagsSetting.Orientation, Enum.BagsOrientation.Horizontal)
        local bagWidth = BagsBar and BagsBar:GetWidth() or 300
        local bagHeight = BagsBar and BagsBar:GetHeight() or 32
        displaySetting(bags, Enum.EditModeBagsSetting.Size, math.min(80*s,
            (g.bagDrawer.w-24)*s/math.max(bagWidth,1)*100,
            (g.bagDrawer.h-10)*s/math.max(bagHeight,1)*100))
        local status = findSystem(layout, E.StatusTrackingBar, 1)
        anchor(status, "BOTTOM", "BOTTOM", leftCenter * s, (g.leftWell.y + g.leftWell.h + 5) * s)
        local second = findSystem(layout, E.StatusTrackingBar, 2)
        anchor(second, "BOTTOM", "BOTTOM", rightCenter * s, (g.rightWell.y + g.rightWell.h + 5) * s)
        local tracking = Enum.EditModeStatusTrackingBarSetting
        if tracking then
            displaySetting(status, tracking.Size, 80 * s)
            displaySetting(second, tracking.Size, 80 * s)
        end
        if not dashboardOnly then
            local objective = findSystem(layout, E.ObjectiveTracker)
            anchor(objective, "TOPRIGHT", "TOPRIGHT", -36 * s, -90 * s)
        end
        if E.MainActionBarEndCap and Enum.EditModeMainActionBarEndCapSetting then
            for _, info in ipairs(layout.systems) do
                if info.system == E.MainActionBarEndCap then
                    displaySetting(info, Enum.EditModeMainActionBarEndCapSetting.Hidden, 1)
                end
            end
        end
        if E.DamageMeter and not dashboardOnly then
            local meter = findSystem(layout, E.DamageMeter)
            anchor(meter, "BOTTOMRIGHT", "BOTTOMRIGHT", -24 * s, 267 * g.density * s)
        end
    end
    -- These are user-tuned in Blizzard Edit Mode. Rebuilding our dashboard
    -- must not reset their saved position, size, aura or tracking settings.
    if base.layoutName == self.layoutName then
        local seatTracking = self.db.arrangeUtility and previousGeometry
            and (not sameGeometry(previousGeometry, g) or previousGeometry.trackingAtWells == false)
        local indices=Enum.EditModeUnitFrameSystemIndices
        for i,info in ipairs(layout.systems or {}) do
            local keep=(info.system==E.StatusTrackingBar and not seatTracking)
                or (info.system==E.UnitFrame and (info.systemIndex==indices.Player
                    or info.systemIndex==indices.Target or info.systemIndex==indices.Focus))
            if keep then
                local original=findSystem(base,info.system,info.systemIndex)
                if original then
                    local kept = SD.Copy(original)
                    if previousGeometry and not sameGeometry(previousGeometry, g)
                        and info.system == E.UnitFrame and self.db.arrangeUnits then
                        rebaseAnchor(kept.anchorInfo, previousGeometry, g)
                        rebaseAnchor(kept.anchorInfo2, previousGeometry, g)
                    end
                    layout.systems[i] = kept
                end
            end
        end
    end
    self:UpgradeDefaultUnitAnchors(layout.systems, g)
    if self.ConfigureNativeParty then
        self:ConfigureNativeParty(findSystem(layout,E.UnitFrame,Enum.EditModeUnitFrameSystemIndices.Party),g)
    end
    if g.variant=="tofu" then self:FinishTofuLayout(layout,g,dashboardOnly) end
    if g.variant=="gulveig" then self:FinishGulveigLayout(layout,g,base.layoutName~=self.layoutName) end
    return layout
end

function SD:SaveAndRefreshLayout(full, index)
    if self.layoutWriteBusy then error("Nested layout save suppressed") end
    self.layoutWriteBusy=true
    local ok,err=pcall(function()
        C_EditMode.SaveLayouts(full)
        if full.activeLayout==index then
            C_EditMode.SetActiveLayout(index==1 and 2 or 1)
            C_EditMode.SetActiveLayout(index)
        end
    end)
    self.layoutWriteBusy=nil
    if not ok then error(err) end
    return true
end

function SD:AlignLayout(previousGeometry)
    local busy, reason = self:IsBusy()
    if busy then SD.Print(reason) return false end
    local full, err = self:GetFullLayouts()
    if not full then SD.Print(err) return false end
    for index, layout in ipairs(full.layouts) do
        if layout.layoutName == self.layoutName then
            local g = self:GetGeometry()
            local previous = previousGeometry or self.db.nativeGeometry
            if previous and previous.trackingAtWells == nil then
                previous = SD.Copy(previous)
                previous.trackingAtWells = false
            end
            full.layouts[index] = self:BuildLayout(layout, g, true, previous)
            local ok = self:Run("Align dashboard", function() self:SaveAndRefreshLayout(full, index) end)
            if ok then
                self.db.nativeGeometry = geometryStamp(g)
                self:RefreshPanels()
                self:SchedulePrecisionAlignment()
                SD.Print("Dashboard aligned. Your unit-frame and chat adjustments were preserved.")
            end
            return ok
        end
    end
    return self:InstallLayout()
end

function SD:ApplyBarVisibility()
    if not Settings or not Settings.GetValue or not Settings.SetValue then
        SD.Print("Enable Action Bars 2, 3 and 4 in Blizzard Options if any dashboard rows are missing.")
        return
    end
    if not self.db.useExtraBars then self:RestoreBarVisibility() return end
    StoneDockCharDB.barBackup = StoneDockCharDB.barBackup or {}
    for index = 2, 4 do
        local key = "PROXY_SHOW_ACTIONBAR_" .. index
        local ok, value = pcall(Settings.GetValue, key)
        if ok and value ~= nil then
            if StoneDockCharDB.barBackup[key] == nil then StoneDockCharDB.barBackup[key] = value end
            local changed, err = pcall(Settings.SetValue, key, true)
            if not changed then self:ReportError("Enable Action Bar " .. index, err) end
        else
            SD.Print("Enable Action Bar " .. index .. " in Blizzard Options if that row is missing.")
        end
    end
end

function SD:RestoreBarVisibility()
    local backup = StoneDockCharDB.barBackup
    if not backup then return end
    if not Settings or not Settings.SetValue then
        SD.Print("Original action-bar visibility is saved, but Blizzard Options is not ready to restore it.")
        return
    end
    for key, value in pairs(backup) do
        local ok, err = pcall(Settings.SetValue, key, value)
        if ok then backup[key] = nil else self:ReportError("Restore action-bar visibility", err) end
    end
    if next(backup) == nil then StoneDockCharDB.barBackup = nil end
end

function SD:InstallLayout()
    local busy, reason = self:IsBusy()
    if busy then SD.Print(reason) return false end
    local full, err, presetCount = self:GetFullLayouts()
    if not full then SD.Print(err) return false end
    local existing, accountCount
    accountCount = 0
    for index, layout in ipairs(full.layouts) do
        if layout.layoutType == Enum.EditModeLayoutType.Account then accountCount = accountCount + 1 end
        if layout.layoutName == self.layoutName then existing = index end
    end
    if existing then
        SD.Print("Your StoneDock layout already exists. Choose Rebuild in settings to replace its placement, or switch to it in Edit Mode.")
        return false
    end
    local maximum = Constants and Constants.EditModeConsts and Constants.EditModeConsts.EditModeMaxLayoutsPerType or 5
    if accountCount >= maximum then
        SD.Print("Your account layout slots are full. Free one in Blizzard Edit Mode, then try again. No layouts were changed.")
        return false
    end
    local active = full.layouts[full.activeLayout]
    local source = active
    if not source or (Enum.InputDeviceInterfaceType and source.interfaceStyle == Enum.InputDeviceInterfaceType.Gamepad) then
        source = full.layouts[1]
    end
    if not source or not source.systems then SD.Print("A keyboard-and-mouse base layout is not ready.") return false end
    local candidate = self:BuildLayout(source)
    local previous = { name = active and active.layoutName, type = active and active.layoutType, index = full.activeLayout }
    local insertAt = presetCount + accountCount + 1
    table.insert(full.layouts, insertAt, candidate)
    -- Inserting before character layouts shifts their global indices.
    if full.activeLayout >= insertAt then full.activeLayout = full.activeLayout + 1 end
    local ok = self:Run("Create layout", function() C_EditMode.SaveLayouts(full) end)
    if not ok then return false end
    -- Keep the recovery record as soon as saving succeeds, even if activating
    -- subsequently fails. The original layout has not been overwritten.
    StoneDockCharDB.previousLayout = previous
    StoneDockCharDB.installed = true
    local activated = self:Run("Activate new layout", function() C_EditMode.OnLayoutAdded(insertAt, true, true) end)
    if not activated then
        SD.Print("The layout was saved. You can select it manually in Blizzard Edit Mode.")
        return false
    end
    self.db.enabled = true
    self.db.nativeGeometry = geometryStamp(self:GetGeometry())
    self:ApplyBarVisibility()
    self:RefreshPanels()
    self:SchedulePrecisionAlignment()
    SD.Print(self.layoutName.." layout created. Your previous layout is still available. /stonedock restore switches back.")
    return true
end

function SD:RebuildLayout()
    local busy, reason = self:IsBusy()
    if busy then SD.Print(reason) return false end
    local full, err = self:GetFullLayouts()
    if not full then SD.Print(err) return false end
    for index, layout in ipairs(full.layouts) do
        if layout.layoutName == self.layoutName then
            local g = self:GetGeometry()
            full.layouts[index] = self:BuildLayout(layout, g, false, self.db.nativeGeometry)
            local ok = self:Run("Rebuild layout", function()
                self:SaveAndRefreshLayout(full, index)
            end)
            if ok then
                self.db.nativeGeometry = geometryStamp(g)
                if self:IsOurLayoutActive() then self:ApplyBarVisibility() end
                self:RefreshPanels()
                self:SchedulePrecisionAlignment()
                SD.Print("StoneDock placement updated. Your other layouts were preserved.")
            end
            return ok
        end
    end
    return self:InstallLayout()
end

function SD:ActivateLayout()
    local busy, reason = self:IsBusy()
    if busy then SD.Print(reason) return end
    local full, err = self:GetFullLayouts()
    if not full then SD.Print(err) return end
    for index, layout in ipairs(full.layouts) do
        if layout.layoutName == self.layoutName then
            self.db.enabled = true
            local previous = full.layouts[full.activeLayout]
            local ok = self:Run("Select layout", function() C_EditMode.SetActiveLayout(index) end)
            if ok and previous and previous.layoutName ~= self.layoutName then
                StoneDockCharDB.previousLayout = { name = previous.layoutName, type = previous.layoutType, index = full.activeLayout }
            end
            if self:IsOurLayoutActive() then self:ApplyBarVisibility() end
            self:RefreshPanels()
            return
        end
    end
    self:InstallLayout()
end

function SD:RestoreLayout()
    local busy, reason = self:IsBusy()
    if busy then SD.Print(reason) return end
    local full, err = self:GetFullLayouts()
    if not full then SD.Print(err) return end
    local previous = StoneDockCharDB.previousLayout
    local index
    if previous then
        for candidate, layout in ipairs(full.layouts) do
            if layout.layoutName == previous.name and layout.layoutType == previous.type then index = candidate break end
        end
    end
    local fallback = not index
    if fallback then index = 1 end
    local ok = self:Run("Restore layout", function() C_EditMode.SetActiveLayout(index) end)
    if ok then
        self:RestoreBarVisibility()
        self.db.enabled = false
        self:RefreshPanels()
        if fallback then
            SD.Print("The previous layout was unavailable; selected the first Blizzard preset. StoneDock is kept for later.")
        else
            SD.Print("Previous layout selected; stone panels hidden. Your StoneDock layout is kept for later.")
        end
    end
end

function SD:ExportLayout()
    local busy, reason = self:IsBusy()
    if busy then SD.Print(reason) return end
    local full, err = self:GetFullLayouts()
    if not full then SD.Print(err) return end
    local source = full.layouts[full.activeLayout] or full.layouts[1]
    local candidate = self:BuildLayout(source)
    local ok, text = self:Run("Export layout", function() return C_EditMode.ConvertLayoutInfoToString(candidate) end)
    if ok then self:ShowCopyDialog("Native Edit Mode layout", text) end
end
